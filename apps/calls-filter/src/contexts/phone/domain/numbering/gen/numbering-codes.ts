/**
 * One prefix of the world's numbering, with the narrower prefixes inside it. A number
 * belongs to the deepest node whose mask covers it: descend into the child that covers
 * it, and stop where none does (`+7*` → `+7963*` → `+7963000*`). Children lie inside
 * their parent's mask and never overlap one another.
 */
export interface INumberingMask {
  readonly mask: string;
  readonly countryCode?: TNumberingCountry;
  readonly networkOperatorCode?: TNumberingOperator;
  readonly stateCodes?: readonly TNumberingState[];
  readonly serviceCode?: TNumberingService;
  readonly children?: readonly INumberingMask[];
}
